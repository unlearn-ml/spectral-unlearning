from __future__ import annotations
import argparse
import csv
import json
import re
import sys
from collections import defaultdict
from functools import lru_cache
from pathlib import Path
from statistics import mean, pstdev

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'src'))
from tofu_scores import table_scores

METHODS = [
    ('GradDiff', 'GD-AdamW'),
    ('SOGradDiff', 'GD-Sophia'),
    ('SPGradDiff_soap_muon', 'SU-GD-Muon'),
    ('SPGradDiff_soap_klshampoo', 'SU-GD-KLShampoo'),
    ('SPGradDiff', 'SU-GD-SOAP'),
    ('NPO', 'NPO-AdamW'),
    ('SONPO', 'NPO-Sophia'),
    ('SPNPO_soap_muon', 'SU-NPO-Muon'),
    ('SPNPO_soap_klshampoo', 'SU-NPO-KLShampoo'),
    ('SPNPO_bf16_fast', 'SU-NPO-SOAP'),
    ('RMU', 'RMU-AdamW'),
    ('SORMU', 'RMU-Sophia'),
    ('SPRMU_soap_muon', 'SU-RMU-Muon'),
    ('SPRMU_soap_klshampoo', 'SU-RMU-KLShampoo'),
    ('SPRMU', 'SU-RMU-SOAP'),
]
METHOD_NAMES = [m[0] for m in METHODS]
PRETTY = dict(METHODS)

MODELS = ['Llama-3.2-1B-Instruct', 'Llama-3.2-3B-Instruct']
SPLITS = ['forget10', 'forget05', 'forget01']
RETAIN = {'forget10': 'retain90', 'forget05': 'retain95', 'forget01': 'retain99'}

TASK_PAT = re.compile(
    r'^tofu_'
    r'(?P<model>Llama-3\.2-[13]B-Instruct)_'
    r'(?P<split>forget\d{2})_'
    r'(?P<method>[A-Za-z0-9_]+?)'
    r'_lr(?P<lr>[0-9eE\.\-+]+)'
    r'_s(?P<seed>\d+)$'
)


def parse_task_name(task: str):
    m = TASK_PAT.match(task)
    if not m:
        return None
    method = m.group('method')
    if method not in METHOD_NAMES or m.group('split') not in RETAIN:
        return None
    return {
        'model': m.group('model'),
        'split': m.group('split'),
        'method': method,
        'lr': m.group('lr'),
        'seed': int(m.group('seed')),
    }


@lru_cache(maxsize=6)
def load_reference(path: Path):
    with path.open() as f:
        return json.load(f)


def gather(saves_dir: Path, reference_dir: Path = ROOT / 'saves/eval', splits=SPLITS):
    out = defaultdict(dict)
    for task_dir in sorted(saves_dir.iterdir()):
        if not task_dir.is_dir():
            continue
        info = parse_task_name(task_dir.name)
        if info is None or info['split'] not in splits:
            continue
        ref_path = reference_dir / f"tofu_{info['model']}_{RETAIN[info['split']]}" / 'TOFU_EVAL.json'
        for eval_dir in sorted(task_dir.glob(f"evals_{info['split']}*")):
            raw = eval_dir / 'TOFU_EVAL.json'
            if not raw.exists():
                if (eval_dir / 'TOFU_SUMMARY.json').is_file():
                    raise ValueError(f'{raw} is required to rescore the per-example truth ratios')
                continue
            with raw.open() as f:
                log = json.load(f)
            try:
                scores = table_scores(log, load_reference(ref_path))
            except (KeyError, TypeError, ValueError) as error:
                raise ValueError(f'Cannot score {raw} with {ref_path}: {error}') from error
            key = (info['model'], info['split'], info['method'], info['lr'])
            out[key][info['seed']] = scores
            break
    return out


def best_lr_per_cell(grouped, required_seeds=None):
    by_method = defaultdict(dict)
    for (model, split, method, lr), seed_scores in grouped.items():
        if required_seeds is not None:
            if not required_seeds.issubset(seed_scores):
                continue
            seed_scores = {seed: seed_scores[seed] for seed in sorted(required_seeds)}
        by_method[(model, split, method)][lr] = list(seed_scores.values())
    best = {}
    for cell, lr_to_scores in by_method.items():
        best_lr, best_agg, best_scores = None, -float('inf'), None
        for lr, scores in lr_to_scores.items():
            if not scores:
                continue
            agg_mean = mean(s[0] for s in scores)
            if agg_mean > best_agg:
                best_agg = agg_mean
                best_lr = lr
                best_scores = scores
        if best_lr is not None:
            best[cell] = (best_lr, best_scores)
    return best


def fmt_cell(scores):
    if not scores:
        return ('--',) * 4
    if len(scores) == 1:
        return tuple(f'{value:.3f}' for value in scores[0])
    cols = []
    for i in range(4):
        vals = [s[i] for s in scores]
        m = mean(vals)
        s = pstdev(vals)
        cols.append(f'{m:.3f}\\,$\\pm$\\,{s:.3f}')
    return tuple(cols)


def render_latex(best, out_path: Path, splits=SPLITS):
    lines = []
    lines.append('% Generated by aggregate_results.py')
    lines.append('\\begin{table*}[t]')
    lines.append('\\centering\\footnotesize')
    lines.append('\\setlength{\\tabcolsep}{3pt}')
    if all(len(scores) == 1 for _, scores in best.values()):
        lines.append('\\caption{TOFU results: best-LR Agg/Mem/Priv/Util (one seed per configuration).}')
    else:
        lines.append('\\caption{TOFU main results: best-LR Agg/Mem/Priv/Util (mean$\\pm$std over seeds).}')
    lines.append('\\label{tab:main-tofu}')
    cols = 'l' + 'cccc' * len(splits)
    lines.append('\\begin{tabular}{' + cols + '}')
    lines.append('\\toprule')
    header = 'Method'
    for split in splits:
        header += ' & \\multicolumn{4}{c}{' + split.replace('forget', 'Forget ') + '\\%}'
    lines.append(header + ' \\\\')
    sub = ''
    for _ in splits:
        sub += ' & Agg & Mem & Priv & Util'
    lines.append(sub + ' \\\\')
    lines.append('\\midrule')
    for model in MODELS:
        lines.append(
            '\\multicolumn{' + str(1 + 4 * len(splits)) + '}{l}{\\emph{' + model + '}}\\\\'
        )
        for trainer_name, _ in METHODS:
            row = [PRETTY[trainer_name]]
            for split in splits:
                key = (model, split, trainer_name)
                if key in best:
                    _, scores = best[key]
                    row += list(fmt_cell(scores))
                else:
                    row += ['--'] * 4
            lines.append(' & '.join(row) + ' \\\\')
        lines.append('\\midrule')
    lines[-1] = '\\bottomrule'
    lines.append('\\end{tabular}')
    lines.append('\\end{table*}')
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text('\n'.join(lines) + '\n')
    print(f'wrote {out_path}')


def render_compact(best, out_path: Path, seed: int):
    rows = []
    latex_rows = []
    order = {name: i for i, name in enumerate(METHOD_NAMES)}
    for (model, split, method), (lr, scores) in sorted(
        best.items(), key=lambda item: (item[0][0], item[0][1], order[item[0][2]])
    ):
        if len(scores) != 1:
            raise ValueError('Compact output requires exactly one seed per condition')
        values = [f'{value:.6f}' for value in scores[0]]
        rows.append([model, split, PRETTY[method], lr, str(seed), *values])
        latex_rows.append(' & '.join([
            model.split('-')[2], split.replace('forget', '') + r'\%',
            PRETTY[method], lr, *[f'{value:.4f}' for value in scores[0]]
        ]) + r' \\')
    out_path.parent.mkdir(parents=True, exist_ok=True)
    tsv_path = out_path.with_suffix('.tsv')
    header = ['Model', 'Split', 'Method', 'LR', 'Seed', 'Agg', 'Mem', 'Priv', 'Util']
    with tsv_path.open('w', encoding='utf-8', newline='') as f:
        writer = csv.writer(f, delimiter='\t')
        writer.writerow(header)
        writer.writerows(rows)
    lines = [
        r'\begin{table}[t]',
        r'\centering\footnotesize',
        r'\caption{TOFU results (seed ' + str(seed) +
        r').}',
        r'\begin{tabular}{llllrrrr}',
        r'\toprule',
        r'Model & Forget & Method & LR & Agg & Mem & Priv & Util \\',
        r'\midrule',
        *latex_rows,
        r'\bottomrule',
        r'\end{tabular}',
        r'\end{table}',
    ]
    out_path.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('\t'.join(header))
    for row in rows:
        print('\t'.join(row))
    print(f'wrote {out_path} and {tsv_path}')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--saves-dir', default='saves/unlearn',
                    help='directory containing tofu_<...>/evals_<split>/TOFU_EVAL.json')
    ap.add_argument('--reference-dir', type=Path, default=ROOT / 'saves/eval',
                    help='directory containing the model- and split-matched retain logs')
    ap.add_argument('--output', default='saves/paper_main_table.tex')
    ap.add_argument('--splits', nargs='+', choices=SPLITS, default=['forget10', 'forget05'])
    ap.add_argument('--seeds', nargs='+', type=int,
                    help='only include learning rates containing every specified seed')
    ap.add_argument('--compact', action='store_true',
                    help='write only the selected conditions as single-seed LaTeX and TSV')
    args = ap.parse_args()
    if args.compact and (not args.seeds or len(args.seeds) != 1):
        ap.error('--compact requires exactly one --seeds value')
    grouped = gather(Path(args.saves_dir), args.reference_dir, args.splits)
    best = best_lr_per_cell(grouped, set(args.seeds) if args.seeds else None)
    if not best:
        ap.exit(1, f'No qualifying runs found under {args.saves_dir}\n')
    if args.compact:
        render_compact(best, Path(args.output), args.seeds[0])
    else:
        render_latex(best, Path(args.output), args.splits)


if __name__ == '__main__':
    main()
